    const costs = ok(lookInside(owner, source, { tab: "bookkeeping", section: "costs" })).records;
    expect(costs[0]).toMatchObject({ vehicle: "2019 BMW 3 Series", type: "labour", amount: 100 }); // newest first
    expect(costs[1]).toMatchObject({ type: "parts", label: "Brake discs", category: "Recon", amount: 240, supplier: "Parts Co" });
