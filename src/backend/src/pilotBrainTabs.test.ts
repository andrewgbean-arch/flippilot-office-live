  it("can't be used to probe a hidden field by searching for what's in it", () => {
    for (const probe of ["Secret Lead Name", "07700900222", "secret.lead@example.test", "SECRET LEAD NOTE", "812"]) {
      expect(ok(lookInside(owner, source, { tab: "leads", search: probe })).records, probe).toHaveLength(0);
    }
    expect(ok(lookInside(owner, source, { tab: "inventory", search: "SECRET VEHICLE NOTE" })).total).toBe(0);
  });
